// Keep the historical Chinese defaults for standalone helpers and editor consumers.
export function defaultT(key, values = {}) {
  return (zh[key] ?? key).replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match)
}

// Retain the key so an already-visible local error follows reactive slot language changes.
export function localeError(t, key) {
  return Object.assign(new Error(t(key)), { localeKey: key })
}
